function joinFa(items) {
  const unique = [];
  for (const item of items) {
    if (item && !unique.includes(item)) unique.push(item);
  }
  if (unique.length <= 1) return unique[0] || "";
  if (unique.length === 2) return `${unique[0]} و ${unique[1]}`;
  return `${unique.slice(0, -1).join("، ")} و ${unique[unique.length - 1]}`;
}

function inSerial(rule, serial) {
  if (rule.min != null && serial < rule.min) return false;
  if (rule.max != null && serial > rule.max) return false;
  return true;
}

function fallbackOf(code) {
  const row = FALLBACK[code];
  if (!row) return null;
  return { city: row[0], provinces: row.slice(1) };
}

export function plateTone(usage) {
  switch (usage) {
    case "تاکسی":
    case "عمومی":
    case "کشاورزی":
      return "yellow";
    case "دولتی":
      return "red";
    case "پلیس":
    case "سپاه":
      return "green";
    case "ارتش":
      return "khaki";
    case "وزارت دفاع":
    case "ستاد کل نیروهای مسلح":
      return "blue";
    case "دیپلمات":
    case "سرویس سفارت":
      return "diplomatic";
    default:
      return "white";
  }
}

export function formatPlate({ left, letter, mid, region }) {
  const gap = letter === "الف" ? " " : " ";
  return `${toFa(left)}${gap}${letter}${gap}${toFa(mid)} ایران ${toFa(region)}`;
}

function locationSentence(plate, cities, provinces) {
  const cityText = joinFa(cities);
  const provText = joinFa(provinces);
  if (cities.length === 1 && provinces.length === 1 && cities[0] === provinces[0]) {
    return `پلاک ${plate} از شهر ${cities[0]} است.`;
  }
  if (cities.length === 1 && provinces.length === 1) {
    return `پلاک ${plate} از شهر ${cities[0]} در استان ${provText} است.`;
  }
  if (cities.length === 1) {
    return `پلاک ${plate} از شهر ${cities[0]} است. استان‌ها: ${provText}.`;
  }
  if (cities.length > 1 && provinces.length === 1) {
    return `پلاک ${plate} بین ${cityText} در استان ${provText} مشترک است.`;
  }
  if (cities.length > 1) {
    return `پلاک ${plate} بین ${cityText} مشترک است. استان‌ها: ${provText}.`;
  }
  if (provinces.length === 1) {
    return `پلاک ${plate} مربوط به استان ${provText} است و شهر دقیق از روی این کد جدا نمی‌شود.`;
  }
  return `پلاک ${plate} مربوط به استان‌های ${provText} است و شهر دقیق از روی این کد جدا نمی‌شود.`;
}

function withUsage(sentence, usage) {
  if (!usage || usage === "شخصی") return sentence;
  return `${sentence} نوع: ${usage}.`;
}

function canonLetter(value) {
  let text = toEn(String(value)).trim();
  text = text.replace(/[\u200c\u200d\u0640]/g, "");
  text = text.replace(/ي/g, "ی").replace(/ك/g, "ک").replace(/ة|ۀ/g, "ه");
  text = text.replace(/آ|أ|إ/g, "ا");
  if (text === "الف" || text === "ا") return "الف";
  if (/^d$/i.test(text)) return "D";
  if (/^s$/i.test(text)) return "S";
  return text;
}

function fail(error) {
  return { ok: false, error };
}

export function parseCar(raw) {
  if (raw && typeof raw === "object") {
    const left = toEn(raw.left || "").replace(/\D/g, "");
    const mid = toEn(raw.mid || "").replace(/\D/g, "");
    const region = toEn(raw.region || "").replace(/\D/g, "");
    const letter = canonLetter(raw.letter || "");
    if (left.length !== 2 || mid.length !== 3 || region.length !== 2) {
      return fail("پلاک را کامل وارد کنید.");
    }
    if (!LETTER_SET.has(letter)) return fail("حرف پلاک شناخته نشد.");
    return { ok: true, left, letter, mid, region };
  }

  let text = toEn(String(raw ?? ""));
  text = text.replace(/[\u200c\u200d\u0640]/g, "");
  text = text.replace(/ي/g, "ی").replace(/ك/g, "ک").replace(/ة|ۀ/g, "ه");
  text = text.replace(/آ|أ|إ/g, "ا");
  text = text.replace(/ایران/g, " ");
  text = text.replace(/[|_\-–—./\\]+/g, " ");
  text = text.replace(/[dD]/g, "D").replace(/[sS]/g, "S");
  const compact = text.replace(/\s+/g, "");
  if (!compact) return fail("پلاک را کامل وارد کنید.");

  const tokens = LETTERS.map((item) => item.id)
    .filter((id) => id !== "الف")
    .sort((a, b) => b.length - a.length);
  let found = null;
  const alefAt = compact.indexOf("الف");
  if (alefAt !== -1) {
    if (compact.indexOf("الف", alefAt + 1) !== -1) return fail("فقط یک حرف مجاز است.");
    const rest = `${compact.slice(0, alefAt)}${compact.slice(alefAt + 3)}`;
    if (/\D/.test(rest)) return fail("فقط یک حرف مجاز است.");
    found = { token: "الف", at: alefAt };
  } else {
    for (const token of tokens) {
      const at = compact.indexOf(token);
      if (at === -1) continue;
      if (found) return fail("فقط یک حرف مجاز است.");
      found = { token, at };
    }
  }
  if (!found) return fail("حرف پلاک شناخته نشد.");
  const before = compact.slice(0, found.at).replace(/\D/g, "");
  const after = compact.slice(found.at + found.token.length).replace(/\D/g, "");
  let left;
  let region;
  let mid;
  if (before.length === 2 && after.length === 5) {
    left = before;
    mid = after.slice(0, 3);
    region = after.slice(3);
  } else if (before.length === 4 && after.length === 3) {
    region = before.slice(0, 2);
    left = before.slice(2);
    mid = after;
  } else {
    return fail("ترتیب پلاک درست نیست. نمونه: ۱۲ ب ۳۴۵ ایران ۱۱");
  }
  return { ok: true, left, letter: found.token, mid, region };
}

export function parseMotorcycle(raw) {
  if (raw && typeof raw === "object" && raw.code) {
    const code = toEn(raw.code).replace(/\D/g, "");
    const serial = toEn(raw.serial || "").replace(/\D/g, "");
    if (code.length !== 3 || serial.length !== 5) return fail("پلاک موتور را کامل وارد کنید.");
    return { ok: true, code, serial };
  }
  const digits = toEn(String(raw ?? "")).replace(/\D/g, "");
  if (digits.length !== 8) return fail("پلاک موتور هشت رقم است: سه رقم کد و پنج رقم سری.");
  return { ok: true, code: digits.slice(0, 3), serial: digits.slice(3) };
}

function resolveCar(parts) {
  const serial = Number(parts.left);
  const usage = USAGE.get(parts.letter) || "شخصی";
  const display = formatPlate(parts);
  const tone = plateTone(usage);
  if (RESERVED.has(parts.region)) {
    const sms = `کد ایران ${toFa(parts.region)} ذخیره است و به شهری اختصاص داده نشده.`;
    return {
      ok: true,
      vehicle: "car",
      kind: "reserved",
      usage,
      tone,
      display,
      cities: [],
      provinces: [],
      nearby: [],
      note: "این کد در جدول ملی هنوز منطقهٔ فعالی ندارد.",
      sms,
      canNotify: false,
    };
  }

  const fb = fallbackOf(parts.region);
  if (!fb) {
    const sms = `کد ایران ${toFa(parts.region)} در جدول پلاک ملی پیدا نشد.`;
    return {
      ok: true,
      vehicle: "car",
      kind: "unknown",
      usage,
      tone,
      display,
      cities: [],
      provinces: [],
      nearby: [],
      note: "",
      sms,
      canNotify: false,
    };
  }

  const personal = PERSONAL.has(parts.letter);
  let matches = [];
  let note = "";
  if (personal) {
    const defined = RULES.filter((rule) => rule.code === parts.region && rule.letter === parts.letter);
    const blocksStar = defined.some((rule) => rule.suppressStar);
    matches = defined.filter((rule) => inSerial(rule, serial));
    if (!blocksStar) {
      matches = matches.concat(
        RULES.filter((rule) => rule.code === parts.region && rule.letter === "*" && inSerial(rule, serial)),
      );
    } else if (matches.length === 0 && defined.length > 0) {
      note = "جدول برای این سرشماره شهر را جدا نکرده است.";
    }
    if (matches.length === 0 && !note) {
      note = "این حرف برای کد انتخاب‌شده در جدول شهرستان نیامده است.";
    }
  }

  const cities = [];
  const provinces = [];
  const nearby = [];
  for (const match of matches) {
    if (!cities.includes(match.city)) cities.push(match.city);
    if (!provinces.includes(match.province)) provinces.push(match.province);
  }
  if (cities.length === 1) {
    for (const item of matches[0].nearby || []) {
      if (!nearby.includes(item)) nearby.push(item);
    }
  }

  let kind;
  if (cities.length === 1) kind = "city";
  else if (cities.length > 1) kind = "shared";
  else {
    kind = "province";
    for (const province of fb.provinces) {
      if (!provinces.includes(province)) provinces.push(province);
    }
    if (!personal && fb.city) {
      cities.push(fb.city);
      kind = "city";
      const split = RULES.some((rule) => rule.code === parts.region && rule.letter !== "*");
      if (split) note = "حرف این پلاک شهرستان را جدا نمی‌کند؛ شهر از روی خود کد ایران آمده است.";
      const near = NEARBY[fb.city] || [];
      for (const item of near) if (!nearby.includes(item)) nearby.push(item);
    }
  }

  let sms = locationSentence(display, cities, provinces);
  sms = withUsage(sms, usage);
  if (note) sms = `${sms} ${note}`;
  return {
    ok: true,
    vehicle: "car",
    kind,
    usage,
    tone,
    display,
    cities,
    provinces,
    nearby,
    note,
    sms,
    canNotify: kind === "city" || kind === "shared" || kind === "province",
  };
}

function resolveMotorcycle(parts) {
  const display = `${toFa(parts.code)} ${toFa(parts.serial)}`;
  const provinces = MOTO.get(parts.code) || [];
  if (provinces.length === 0) {
    return {
      ok: true,
      vehicle: "motorcycle",
      kind: "unknown",
      usage: "موتورسیکلت",
      tone: "white",
      display,
      cities: [],
      provinces: [],
      nearby: [],
      note: "",
      sms: `کد موتور ${toFa(parts.code)} در جدول پلاک موتور پیدا نشد.`,
      canNotify: false,
    };
  }
  const kind = provinces.length > 1 ? "shared" : "province";
  const place = provinces.length > 1 ? `استان‌های ${joinFa(provinces)}` : `استان ${provinces[0]}`;
  return {
    ok: true,
    vehicle: "motorcycle",
    kind,
    usage: "موتورسیکلت",
    tone: "white",
    display,
    cities: [],
    provinces: [...provinces],
    nearby: [],
    note: "کد موتور استان را می‌گوید و شهر را جدا نمی‌کند.",
    sms: `پلاک موتور ${display} مربوط به ${place} است. کد موتور شهر را جدا نمی‌کند.`,
    canNotify: true,
  };
}

export function resolvePlate(input, options = {}) {
  const vehicle = options.vehicle || (input && input.vehicle) || "car";
  if (vehicle === "motorcycle") {
    const parsed = parseMotorcycle(input);
    if (!parsed.ok) return parsed;
    return resolveMotorcycle(parsed);
  }
  const parsed = parseCar(input);
  if (!parsed.ok) return parsed;
  return resolveCar(parsed);
}

export function normalizePhone(raw) {
  let digits = toEn(String(raw ?? "")).replace(/\D/g, "");
  if (digits.startsWith("0098")) digits = `0${digits.slice(4)}`;
  else if (digits.startsWith("98") && digits.length === 12) digits = `0${digits.slice(2)}`;
  if (/^09\d{9}$/.test(digits)) return digits;
  return null;
}

export function catalog() {
  const byProvince = new Map();
  const ensure = (province) => {
    if (!byProvince.has(province)) byProvince.set(province, new Map());
    return byProvince.get(province);
  };
  const put = (province, city, code) => {
    const cities = ensure(province);
    if (!cities.has(city)) cities.set(city, new Set());
    cities.get(city).add(code);
  };
  for (const rule of RULES) put(rule.province, rule.city, rule.code);
  const coded = new Set(RULES.map((rule) => rule.code));
  for (const [code, row] of Object.entries(FALLBACK)) {
    if (coded.has(code)) continue;
    const city = row[0] || "بدون تفکیک شهرستان";
    put(row[1], city, code);
  }
  return [...byProvince.entries()]
    .map(([province, cities]) => ({
      province,
      cities: [...cities.entries()]
        .map(([city, codes]) => ({
          city,
          codes: [...codes].sort((a, b) => a.localeCompare(b, "fa")),
        }))
        .sort((a, b) => a.city.localeCompare(b.city, "fa")),
    }))
    .sort((a, b) => a.province.localeCompare(b.province, "fa"));
}
